    private string? FindBestMatch(string sourceColumn, List<string> targetColumns, ColumnMatchingOptions options, HashSet<string> availableTargets)
    {
        string? bestMatch = null;
        int bestScore = 0;

        foreach (var targetColumn in targetColumns)
        {
            if (!availableTargets.Contains(targetColumn))
                continue; // Already mapped

            var score = CalculateSimilarity(sourceColumn, targetColumn, options);

            if (score >= options.MinimumSimilarityScore && score > bestScore)
            {
                bestScore = score;
                bestMatch = targetColumn;
            }
        }

        return bestMatch;
    }

    private string NormalizeColumnName(string columnName, ColumnMatchingOptions options)
    {
        var normalized = columnName;

        if (options.IgnoreCase)
        {
            normalized = normalized.ToLowerInvariant();
        }

        if (options.IgnoreUnderscores)
        {
            normalized = normalized.Replace("_", "");
        }

        if (options.IgnoreSpaces)
        {
            normalized = normalized.Replace(" ", "");
        }

        return normalized;
    }

    private double CalculateConfidenceScore(ColumnMappingAnalysis analysis, TableSchema targetSchema)
    {
        if (analysis.Mappings.Count == 0)
            return 0.0;

        // Factor 1: Percentage of source columns mapped
        double mappedRatio = (double)analysis.Mappings.Count / (analysis.Mappings.Count + analysis.UnmappedSourceColumns.Count);

        // Factor 2: All required target columns are mapped
        double requiredMapped = analysis.UnmappedTargetColumns.Count == 0 ? 1.0 : 0.5;

        // Factor 3: No validation errors
        double noErrors = analysis.ValidationErrors.Count == 0 ? 1.0 : 0.7;

        return (mappedRatio * 0.4) + (requiredMapped * 0.4) + (noErrors * 0.2);
    }

    private int LevenshteinDistance(string source, string target)
    {
        if (string.IsNullOrEmpty(source))
        {
            return string.IsNullOrEmpty(target) ? 0 : target.Length;
        }

        if (string.IsNullOrEmpty(target))
        {
            return source.Length;
        }

        var distance = new int[source.Length + 1, target.Length + 1];

        for (var i = 0; i <= source.Length; i++)
        {
            distance[i, 0] = i;
        }

        for (var j = 0; j <= target.Length; j++)
        {
            distance[0, j] = j;
        }

        for (var i = 1; i <= source.Length; i++)
        {
            for (var j = 1; j <= target.Length; j++)
            {
                var cost = target[j - 1] == source[i - 1] ? 0 : 1;
                distance[i, j] = Math.Min(
                    Math.Min(distance[i - 1, j] + 1, distance[i, j - 1] + 1),
                    distance[i - 1, j - 1] + cost);
            }
        }

        return distance[source.Length, target.Length];
    }
}
