using Microsoft.Extensions.Logging;
using Platform.Application.DTOs.Import;
using Platform.Application.Services;

namespace Platform.Infrastructure.Services;

/// <summary>
/// Implementation of column mapping service with fuzzy matching
/// </summary>
public class ColumnMappingService : IColumnMappingService
{
    private readonly ILogger<ColumnMappingService> _logger;

    public ColumnMappingService(ILogger<ColumnMappingService> logger)
    {
        _logger = logger;
    }

    public async Task<ColumnMappingAnalysis> AnalyzeAndMapColumnsAsync(
        List<string> sourceColumns,
        TableSchema targetSchema,
        ColumnMatchingOptions? options = null)
    {
        options ??= new ColumnMatchingOptions();
        var analysis = new ColumnMappingAnalysis();

        var targetColumns = targetSchema.Columns.Select(c => c.ColumnName).ToList();
        var unmappedTargets = new HashSet<string>(targetColumns);

        // Try to auto-map each source column
        foreach (var sourceColumn in sourceColumns)
        {
            var bestMatch = FindBestMatch(sourceColumn, targetColumns, options, unmappedTargets);

            if (bestMatch != null)
            {
                var targetColumn = targetSchema.Columns.First(c => c.ColumnName == bestMatch);
                analysis.Mappings.Add(new ColumnMappingDefinition
                {
                    SourceColumn = sourceColumn,
                    TargetColumn = bestMatch,
                    IsRequired = targetColumn.IsRequired
                });
                unmappedTargets.Remove(bestMatch);
            }
            else
            {
                // No good match found
                analysis.UnmappedSourceColumns.Add(sourceColumn);
            }
        }

        // Identify required target columns that weren't mapped
        // Exclude auto-generated columns as they don't need to be provided by user
        analysis.UnmappedTargetColumns = unmappedTargets
            .Where(t =>
            {
                var column = targetSchema.Columns.First(c => c.ColumnName == t);
                return column.IsRequired && !column.IsAutoGenerated;
            })
            .ToList();

        // Calculate confidence score
        analysis.ConfidenceScore = CalculateConfidenceScore(analysis, targetSchema);

        _logger.LogInformation("Column mapping analysis complete: {MappedCount} mapped, {UnmappedSourceCount} unmapped sources, {UnmappedTargetCount} unmapped required targets",
            analysis.Mappings.Count, analysis.UnmappedSourceColumns.Count, analysis.UnmappedTargetColumns.Count);

        await Task.CompletedTask; // To satisfy async signature
        return analysis;
    }

    public async Task<(bool IsValid, List<string> Errors)> ValidateMappingsAsync(
        ColumnMappingAnalysis mappings,
        TableSchema targetSchema)
    {
        var errors = new List<string>();

        // Check that all required target columns are mapped (excluding auto-generated ones)
        var requiredColumns = targetSchema.Columns
            .Where(c => c.IsRequired && !c.IsAutoGenerated)
            .Select(c => c.ColumnName)
            .ToHashSet();
        var mappedTargets = mappings.Mappings.Select(m => m.TargetColumn).ToHashSet();

        foreach (var required in requiredColumns)
        {
            if (!mappedTargets.Contains(required))
            {
                errors.Add($"Required column '{required}' is not mapped");
            }
        }

        // Check for duplicate target mappings
        var duplicates = mappings.Mappings
            .GroupBy(m => m.TargetColumn)
            .Where(g => g.Count() > 1)
            .Select(g => g.Key);

        foreach (var duplicate in duplicates)
        {
            errors.Add($"Column '{duplicate}' is mapped multiple times");
        }

        // Validate transformations
        foreach (var mapping in mappings.Mappings.Where(m => m.Transformation != null))
        {
            // Transformation validation would go here
            // For now, just check that it exists
            if (string.IsNullOrWhiteSpace(mapping.Transformation!.TransformationType))
            {
                errors.Add($"Invalid transformation for mapping {mapping.SourceColumn} -> {mapping.TargetColumn}");
            }
        }

        await Task.CompletedTask; // To satisfy async signature
        return (errors.Count == 0, errors);
    }

    public int CalculateSimilarity(string source, string target, ColumnMatchingOptions options)
    {
        // Normalize the strings based on options
        var normalizedSource = NormalizeColumnName(source, options);
        var normalizedTarget = NormalizeColumnName(target, options);

        // Exact match
        if (normalizedSource == normalizedTarget)
        {
            return 100;
        }

        // Calculate Levenshtein distance
        var distance = LevenshteinDistance(normalizedSource, normalizedTarget);
        var maxLength = Math.Max(normalizedSource.Length, normalizedTarget.Length);

        if (maxLength == 0) return 100;

        var similarity = (1.0 - (double)distance / maxLength) * 100;

        // Boost score if one string contains the other
        if (normalizedSource.Contains(normalizedTarget) || normalizedTarget.Contains(normalizedSource))
        {
            similarity = Math.Min(100, similarity + 20);
        }

        return (int)Math.Round(similarity);
    }

